def resolve_lang(query_lang: str | None, cookie_lang: str | None,
                 accept_language: str | None) -> str:
    """Vybere jazyk: ?lang= → cookie → hlavička Accept-Language → výchozí."""
    for candidate in (query_lang, cookie_lang):
        if candidate in TRANSLATIONS:
            return candidate
    if accept_language:
        for part in accept_language.split(","):
            code = part.split(";")[0].strip().lower()[:2]
            if code in TRANSLATIONS:
                return code
    return DEFAULT_LANG


def translations(lang: str) -> dict[str, str]:
    """Slovník pro daný jazyk; chybějící klíče doplní z výchozího jazyka."""
    base = dict(TRANSLATIONS[DEFAULT_LANG])
    base.update(TRANSLATIONS.get(lang, {}))
    return base
